// Development-only Flutter SDK cache for diagnostic fixture acceptance. Downloads one
// pinned stable archive, verifies its published SHA-256 and keeps Flutter, Dart, pub,
// Gradle and Android user state inside the cache. `--remove` deletes only that cache.
import {createHash, randomUUID} from 'node:crypto';
import {createReadStream, createWriteStream} from 'node:fs';
import {access, chmod, mkdir, mkdtemp, readFile, rename, rm, writeFile} from 'node:fs/promises';
import {homedir} from 'node:os';
import {isAbsolute, join, resolve} from 'node:path';
import {execFile, spawn} from 'node:child_process';
import {Readable, Transform} from 'node:stream';
import {pipeline} from 'node:stream/promises';
import {pathToFileURL} from 'node:url';
import {promisify} from 'node:util';

// From the official releases_macos.json (stable, released 2026-10-29).
export const release = {
  version: '3.47.9', revision: 'c197ca5199e9ee5661e865596c9c07294dfab51c', dart: '3.13.7',
  baseURL: 'https://storage.googleapis.com/flutter_infra_release/releases',
  archives: {
    x64: {path: 'stable/macos/flutter_macos_3.47.9-stable.zip', sha256: '0dc38b4038a0b002a6258696a5b327a58473c175c9e334b9f329ef7d79a4fdcd'},
    arm64: {path: 'stable/macos/flutter_macos_arm64_3.47.9-stable.zip', sha256: '6545b85938745dc5070e9faf2adf70233c1811009d87fe6d27bfcda5a04b7698'},
  },
};
const MARKER = 'testrun-flutter-cache.json', ARCHIVE_LIMIT = 3 * 1024 ** 3;

async function exists(path) {
  try { await access(path); return true; } catch (error) { if (error.code === 'ENOENT') return false; throw error; }
}
async function digest(path) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(path)) hash.update(chunk);
  return hash.digest('hex');
}
async function run(program, args, env) {
  await new Promise((accept, reject) => {
    const child = spawn(program, args, {env, stdio: 'inherit'});
    child.once('error', reject);
    child.once('close', (code, signal) => code === 0 ? accept() : reject(new Error(`${program} exited ${code ?? signal}`)));
  });
}
async function output(program, args, env) {
  return (await promisify(execFile)(program, args, {env, timeout: 600000, maxBuffer: 4194304})).stdout;
}
export function defaultCache(home = homedir()) { return join(home, 'Library/Caches/testrun/development/flutter'); }

/** Owned state locations; the launcher exports them for every Flutter invocation. */
export function layout(cache, pinned = release) {
  return {sdk: join(cache, `sdk-${pinned.version}`, 'flutter'), launcher: join(cache, 'bin/flutter'),
    home: join(cache, 'home'), pubCache: join(cache, 'pub-cache'), gradleHome: join(cache, 'gradle-home'),
    androidUserHome: join(cache, 'android-user-home'), archives: join(cache, 'archives')};
}
function launcherScript(paths) {
  const q = value => `'${value.replaceAll("'", "'\\''")}'`;
  return ['#!/bin/sh', '# Generated by setup-diagnostic-flutter.mjs; state stays in the Testrun development cache.',
    `export HOME=${q(paths.home)}`, `export PUB_CACHE=${q(paths.pubCache)}`, `export GRADLE_USER_HOME=${q(paths.gradleHome)}`,
    `export ANDROID_USER_HOME=${q(paths.androidUserHome)}`, 'export FLUTTER_SUPPRESS_ANALYTICS=true', 'export CI=true',
    `exec ${q(join(paths.sdk, 'bin/flutter'))} "$@"`, ''].join('\n');
}

// Dependencies are injectable so download/refusal tests need no network or SDK.
export async function setup({cache, arch = process.arch, platform = process.platform, pinned = release,
  fetcher = fetch, runner = run, reader = output, env = process.env}) {
  if (platform !== 'darwin') throw new Error('This Flutter cache workflow supports macOS hosts');
  if (!cache || !isAbsolute(cache)) throw new Error('Select an absolute Flutter cache path');
  const selected = pinned.archives[arch === 'arm64' ? 'arm64' : 'x64'];
  const paths = layout(cache, pinned);
  await mkdir(cache, {recursive: true, mode: 0o700});
  const marker = join(cache, MARKER);
  if (await exists(marker)) {
    if (JSON.parse(await readFile(marker, 'utf8')).owner !== 'testrun-development-flutter') throw new Error(`Unrecognized Flutter cache marker: ${marker}`);
  } else await writeFile(marker, JSON.stringify({owner: 'testrun-development-flutter', version: pinned.version, revision: pinned.revision}, null, 2) + '\n', {flag: 'wx'});
  for (const path of [paths.archives, paths.home, paths.pubCache, paths.gradleHome, paths.androidUserHome, join(cache, 'bin')]) await mkdir(path, {recursive: true, mode: 0o700});
  const archive = join(paths.archives, selected.path.split('/').pop());
  if (!await exists(archive)) {
    console.log(`Downloading Flutter ${pinned.version} into ${cache}`);
    const partial = `${archive}.${randomUUID()}.partial`;
    try {
      const response = await fetcher(`${pinned.baseURL}/${selected.path}`, {signal: AbortSignal.timeout(1800000)});
      if (!response.ok || !response.body) throw new Error(`Flutter download failed: HTTP ${response.status}`);
      let bytes = 0;
      const bound = new Transform({transform(chunk, encoding, callback) {
        bytes += chunk.length;
        callback(bytes > ARCHIVE_LIMIT ? new Error('Flutter archive exceeded 3 GiB') : null, chunk);
      }});
      await pipeline(Readable.fromWeb(response.body), bound, createWriteStream(partial, {flags: 'wx', mode: 0o600}));
      if (await digest(partial) !== selected.sha256) throw new Error('Flutter archive checksum mismatch');
      await rename(partial, archive);
    } finally { await rm(partial, {force: true}); }
  }
  // Revalidate cached bytes before extracting or using them.
  if (await digest(archive) !== selected.sha256) throw new Error(`Cached Flutter archive checksum mismatch: ${archive}`);
  if (!await exists(join(paths.sdk, 'bin/flutter'))) {
    const staging = await mkdtemp(join(cache, '.flutter-extract-'));
    try {
      await runner('/usr/bin/unzip', ['-q', archive, '-d', staging], env);
      if (!await exists(join(staging, 'flutter/bin/flutter'))) throw new Error('Flutter archive lacks its expected executable');
      await mkdir(join(cache, `sdk-${pinned.version}`), {recursive: true, mode: 0o700});
      await rename(join(staging, 'flutter'), paths.sdk);
    } finally { await rm(staging, {recursive: true, force: true}); }
  }
  await writeFile(paths.launcher, launcherScript(paths), {mode: 0o700});
  await chmod(paths.launcher, 0o700);
  const flutterEnv = {...env, PATH: `${join(paths.sdk, 'bin')}:${env.PATH ?? '/usr/bin:/bin'}`};
  await runner(paths.launcher, ['--disable-analytics'], flutterEnv);
  // A first run can print tool-build progress before the machine-readable object.
  const printed = await reader(paths.launcher, ['--version', '--machine'], flutterEnv);
  const version = JSON.parse(printed.slice(printed.indexOf('{')));
  if (version.frameworkVersion !== pinned.version || version.frameworkRevision !== pinned.revision || !String(version.dartSdkVersion).startsWith(pinned.dart)) {
    throw new Error(`Extracted Flutter identity differs from the pinned release: ${JSON.stringify(version)}`);
  }
  // Fetch Android engine artifacts here, so later builds need no SDK downloads.
  await runner(paths.launcher, ['precache', '--android', '--no-ios', '--no-web', '--no-macos', '--no-linux', '--no-windows', '--no-fuchsia', '--no-universal'], flutterEnv);
  return {flutter: pinned.version, revision: pinned.revision, dart: version.dartSdkVersion, cache, launcher: paths.launcher, sdk: paths.sdk, archiveSha256: selected.sha256};
}

/** Delete one owned Flutter cache, recognized by its marker. Nothing else is touched. */
export async function remove({cache}) {
  if (!cache || !isAbsolute(cache)) throw new Error('Select an absolute Flutter cache path');
  const marker = join(cache, MARKER);
  if (!await exists(marker)) throw new Error(`No Testrun Flutter cache marker in ${cache}; nothing was removed`);
  if (JSON.parse(await readFile(marker, 'utf8')).owner !== 'testrun-development-flutter') throw new Error(`Unrecognized Flutter cache marker: ${marker}; nothing was removed`);
  await rm(cache, {recursive: true, force: true});
  return {removed: cache};
}

async function main() {
  const [mode, selectedCache] = process.argv.slice(2);
  const cache = selectedCache || defaultCache();
  if (mode === '--remove') console.log(JSON.stringify(await remove({cache}), null, 2));
  else if (mode === 'setup') console.log(JSON.stringify(await setup({cache}), null, 2));
  else throw new Error('Usage: setup-diagnostic-flutter.mjs setup|--remove [/absolute/cache]');
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
