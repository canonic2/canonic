// Rebuild the browser-only AJV helper and its exact input/notice inventory.
import {readFile,writeFile,mkdir,lstat,readdir} from 'node:fs/promises';
import {resolve,relative,isAbsolute,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';

const root=resolve(process.argv[2]??'');
if(!process.argv[2])throw Error('Supply a node_modules directory containing ajv 8.20.0 and esbuild 0.28.0');
const require=createRequire(import.meta.url);
const esbuild=require(resolve(root,'esbuild'));
const ajv=JSON.parse(await readFile(resolve(root,'ajv/package.json'),'utf8'));
if(ajv.name!=='ajv'||ajv.version!=='8.20.0'||esbuild.version!=='0.28.0')throw Error('Pinned AJV/esbuild versions changed');
const built=await esbuild.build({entryPoints:[resolve(root,'ajv/dist/ajv.js')],bundle:true,write:false,format:'iife',globalName:'__testrunAjv',platform:'browser',target:'es2022',minify:true,metafile:true,legalComments:'none'});
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const files=[];const packages=new Set();
for(const path of Object.keys(built.metafile.inputs).sort()){
  const absolute=resolve(path),name=relative(root,absolute).replaceAll('\\','/');
  if(name.startsWith('../')||isAbsolute(name))throw Error('Bundler read outside the selected dependency root');
  const bytes=await readFile(absolute);files.push({path:name,bytes:bytes.length,sha256:sha(bytes)});
  packages.add(name.startsWith('@')?name.split('/').slice(0,2).join('/'):name.split('/')[0]);
}
const output=`// Generated by tools/browser-developer-validator.mjs; see developer-validator-source.json.\n// Third-party notices: third-party/browser/developer-tool-notices/LICENSE.\n(()=>{${built.outputFiles[0].text};return __testrunAjv.default;})()\n`;
const notices=[];const versions=[];
for(const name of [...packages].sort()){
  const path=resolve(root,name),pkg=JSON.parse(await readFile(resolve(path,'package.json'),'utf8'));
  const licenses=(await readdir(path)).filter(name=>/^licen[cs]e(?:\..*)?$/i.test(name)).sort();
  if(!licenses.length)throw Error(`Missing license for ${name}`);
  versions.push({name:pkg.name,version:pkg.version,license:pkg.license});
  for(const license of licenses){
    if(!(await lstat(resolve(path,license))).isFile())throw Error(`License must be a regular file: ${name}/${license}`);
    notices.push(`${pkg.name} ${pkg.version}\n${'='.repeat(72)}\n${await readFile(resolve(path,license),'utf8')}`);
  }
}
const base=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const manifestPath=resolve(base,'src/browser/reading/developer-validator-source.json');
try{
  const pinned=JSON.parse(await readFile(manifestPath,'utf8'));
  if(JSON.stringify(pinned.files)!==JSON.stringify(files)||JSON.stringify(pinned.packages)!==JSON.stringify(versions))throw Error('Pinned validator inputs changed; review and update the source inventory explicitly');
}catch(error){if(error.code!=='ENOENT')throw error;}
async function save(path,value){
  try{if(await readFile(path,'utf8')===value)return;}catch(error){if(error.code!=='ENOENT')throw error;}
  await writeFile(path,value);
}
const noticesPath=resolve(base,'third-party/browser/developer-tool-notices/LICENSE');
await mkdir(dirname(noticesPath),{recursive:true});
await save(resolve(base,'src/browser/reading/developer-validator.js'),output);
await save(manifestPath,`${JSON.stringify({schemaVersion:1,ajv:ajv.version,esbuild:esbuild.version,outputSha256:sha(output),packages:versions,files},null,2)}\n`);
await save(noticesPath,notices.join('\n\n'));
process.stdout.write(`Bundled AJV ${ajv.version}: ${Buffer.byteLength(output)} bytes, ${files.length} pinned inputs.\n`);
