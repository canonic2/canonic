/// First line of the Shield-owned prefix rules file; a file without it is not Shield's.
pub(super) const PREFIX_RULES_HEADER: &str = "# Generated by Shield from the active policy.";

/// Codex `prefix_rule` entries, one per distinct pattern, or None when there are none.
/// Tokens are printable text, so JSON string encoding is a valid Starlark literal.
pub(super) fn prefix_rules(prefixes: &[CodexPrefix]) -> Option<String> {
    let mut patterns: std::collections::BTreeMap<&Vec<Vec<String>>, Vec<&CodexPrefix>> =
        std::collections::BTreeMap::new();
    for prefix in prefixes {
        patterns.entry(&prefix.pattern).or_default().push(prefix);
    }
    if patterns.is_empty() {
        return None;
    }
    let quote = |s: &str| serde_json::to_string(s).expect("string encoding");
    let mut text = format!(
        "{PREFIX_RULES_HEADER}\n# Shield rewrites this file on activation and setup; do not edit it.\n# Shield's hooks still decide every command these prefixes cover.\n"
    );
    for (pattern, owners) in patterns {
        let sources: Vec<String> = owners
            .iter()
            .map(|p| format!("{} {}", p.owner, p.rule))
            .collect();
        let positions: Vec<String> = pattern
            .iter()
            .map(|tokens| match tokens.as_slice() {
                [one] => quote(one),
                many => format!(
                    "[{}]",
                    many.iter().map(|t| quote(t)).collect::<Vec<_>>().join(", ")
                ),
            })
            .collect();
        let example: Vec<String> = pattern.iter().map(|tokens| quote(&tokens[0])).collect();
        writeln!(
            text,
            "\n# {}\nprefix_rule(\n    pattern = [{}],\n    decision = \"allow\",\n    justification = {},\n    match = [[{}]],\n)",
            sources.join(", "),
            positions.join(", "),
            quote(&format!("Shield decides this command ({}).", sources.join(", "))),
            example.join(", "),
        )
        .expect("writing to a String");
    }
    Some(text)
}

/// Codex's tool prompt is the only confirmation before apply activates policy,
/// so apply prompts even when the operator marks it.
const ALWAYS_PROMPT: &str = "policy_apply";

/// The server table; `approved` tools run without asking and the rest prompt.
pub(super) fn mcp(binary: &Path, root: &Path, approved: &[String]) -> String {
    let mut table = Table::new();
    table["command"] = value(binary.to_string_lossy().as_ref());
    table["args"] = value(toml_edit::Array::from_iter([
        "mcp",
        "serve",
        "--project",
        root.to_str().expect("validated root"),
        "--agent",
        "codex",
    ]));
    table["default_tools_approval_mode"] = value("prompt");
    let mut approvals = Table::new();
    for tool in crate::review::mcp::tools_for(Some("codex"))["tools"]
        .as_array()
        .expect("static tool inventory")
    {
        let name = tool["name"].as_str().expect("static tool name");
        let mut entry = Table::new();
        let marked = approved.iter().any(|tool| tool == name);
        entry["approval_mode"] = value(if marked && name != ALWAYS_PROMPT {
            "approve"
        } else {
            "prompt"
        });
        approvals[name] = Item::Table(entry);
    }
    table["tools"] = Item::Table(approvals);
    let mut doc = DocumentMut::new();
    *doc.as_table_mut() = table;
    doc.to_string()
}

fn document(source: Option<&str>) -> Result<DocumentMut, Error> {
    let doc: DocumentMut = source
        .unwrap_or("")
        .parse()
        .map_err(|_| Error::Invalid("invalid Codex TOML"))?;
    if doc.get("mcp_servers").is_some_and(|v| !v.is_table()) {
        return Err(Error::Invalid("Codex mcp_servers must be a table"));
    }
    Ok(doc)
}

pub(super) fn has_mcp_entry(source: &str) -> Result<bool, Error> {
    let doc = document(Some(source))?;
    match doc
        .get("mcp_servers")
        .and_then(|servers| servers.get("shield"))
    {
        Some(entry) if !entry.is_table() => Err(Error::Invalid("Codex Shield MCP must be a table")),
        entry => Ok(entry.is_some()),
    }
}

pub(super) fn merge_mcp(
    before: Option<&str>,
    old: Option<&str>,
    new: Option<&str>,
) -> Result<String, Error> {
    let mut doc = document(before)?;
    if let Some(existing) = doc.get("mcp_servers").and_then(|s| s.get("shield")) {
        let mut expected: DocumentMut = old
            .ok_or(Error::Invalid("unowned Codex Shield MCP table"))?
            .parse()
            .map_err(|_| Error::Invalid("invalid owned MCP table"))?;
        let mut actual = DocumentMut::new();
        actual.as_table_mut().extend(
            existing
                .as_table()
                .ok_or(Error::Invalid("Codex Shield MCP must be a table"))?
                .clone(),
        );
        detach_positions(actual.as_table_mut());
        detach_positions(expected.as_table_mut());
        // Formatting/comments are owned along with the table; unexpected edits conflict.
        if actual.to_string() != expected.to_string() {
            return Err(Error::Invalid(
                "Codex Shield MCP table was manually changed",
            ));
        }
    }
    if let Some(servers) = doc.get_mut("mcp_servers").and_then(Item::as_table_mut) {
        servers.remove("shield");
    }
    if let Some(new) = new {
        if !doc.contains_key("mcp_servers") {
            doc["mcp_servers"] = Item::Table(Table::new());
        }
        let mut parsed: DocumentMut = new
            .parse()
            .map_err(|_| Error::Invalid("invalid desired MCP table"))?;
        // Positions from a standalone document must not interleave these
        // nested tables with the user's existing server tables.
        detach_positions(parsed.as_table_mut());
        doc["mcp_servers"]["shield"] = Item::Table(parsed.as_table().clone());
    }
    Ok(doc.to_string())
}

fn detach_positions(table: &mut Table) {
    table.set_position(None);
    for (_, item) in table.iter_mut() {
        if let Some(child) = item.as_table_mut() {
            detach_positions(child);
        }
    }
}

pub(super) fn diagnose(bytes: Option<&str>, d: &mut Vec<&'static str>) -> Result<(), Error> {
    let doc = document(bytes)?;
    if doc
        .get("mcp_servers")
        .and_then(|s| s.get("shield"))
        .is_none()
    {
        d.push("owned Codex MCP table is missing");
    }
    if doc
        .get("mcp_servers")
        .and_then(|s| s.get("shield"))
        .and_then(|s| s.get("default_tools_approval_mode"))
        .and_then(Item::as_str)
        != Some("prompt")
    {
        d.push("Shield MCP mutations need default approval prompts in Codex");
    }
    let server = doc.get("mcp_servers").and_then(|s| s.get("shield"));
    for tool in crate::review::mcp::tools_for(Some("codex"))["tools"]
        .as_array()
        .expect("static tool inventory")
    {
        let name = tool["name"].as_str().expect("static tool name");
        // Which tools are approved is the operator's choice, except apply; each needs a mode.
        let mode = server
            .and_then(|s| s.get("tools"))
            .and_then(|t| t.get(name))
            .and_then(|t| t.get("approval_mode"))
            .and_then(Item::as_str);
        let valid = if name == ALWAYS_PROMPT {
            mode == Some("prompt")
        } else {
            matches!(mode, Some("approve" | "prompt"))
        };
        if !valid {
            d.push("Shield MCP tool approvals need repair in Codex");
            break;
        }
    }
    if doc
        .get("features")
        .and_then(|s| s.get("hooks"))
        .and_then(Item::as_bool)
        == Some(false)
    {
        d.push("native hooks are disabled in Codex project settings");
    }
    Ok(())
}
