//! Codex TOML MCP serialization, prefix rules, ownership merge and configuration diagnostics.
use crate::{policy::agent_outputs::CodexPrefix, review::Error};
use std::{fmt::Write as _, path::Path};
use toml_edit::{DocumentMut, Item, Table, value};

pub(super) fn connection(
    source: &str,
    alias: &str,
) -> Result<Option<crate::mcp_connections::Transport>, Error> {
    let doc = document(Some(source))?;
    super::super::unambiguous_mcp_alias(
        alias,
        doc.get("mcp_servers")
            .and_then(Item::as_table)
            .into_iter()
            .flat_map(|table| table.iter().map(|(key, _)| key)),
    )?;
    let Some(server) = doc.get("mcp_servers").and_then(|s| s.get(alias)) else {
        return Ok(None);
    };
    let table = server
        .as_table()
        .ok_or(Error::Invalid("MCP connection must be a table"))?;
    if table.iter().any(|(key, _)| {
        ![
            "command",
            "args",
            "env",
            "url",
            "enabled",
            "default_tools_approval_mode",
            "tools",
            "startup_timeout_sec",
            "tool_timeout_sec",
            "enabled_tools",
            "disabled_tools",
        ]
        .contains(&key)
    }) || server
        .get("enabled")
        .is_some_and(|v| v.as_bool() != Some(true))
    {
        return Err(Error::Invalid(
            "unsupported or disabled MCP connection settings",
        ));
    }
    if let Some(url) = server.get("url").and_then(Item::as_str) {
        if server.get("command").is_some()
            || server.get("args").is_some()
            || server.get("env").is_some()
        {
            return Err(Error::Invalid("mixed MCP transport settings"));
        }
        return Ok(Some(crate::mcp_connections::Transport::Http {
            url: url.into(),
        }));
    }
    let command = server
        .get("command")
        .and_then(Item::as_str)
        .ok_or(Error::Invalid("MCP command missing"))?
        .to_owned();
    let args = match server.get("args") {
        None => Vec::new(),
        Some(args) => args
            .as_array()
            .ok_or(Error::Invalid("MCP args must be strings"))?
            .iter()
            .map(|v| {
                v.as_str()
                    .map(str::to_owned)
                    .ok_or(Error::Invalid("MCP args must be strings"))
            })
            .collect::<Result<Vec<_>, _>>()?,
    };
    let env = match server.get("env") {
        None => std::collections::BTreeMap::new(),
        Some(env) => env
            .as_table_like()
            .ok_or(Error::Invalid("MCP env must be a map"))?
            .iter()
            .map(|(k, v)| {
                v.as_str()
                    .map(|v| (k.to_owned(), v.to_owned()))
                    .ok_or(Error::Invalid("MCP env must be strings"))
            })
            .collect::<Result<_, _>>()?,
    };
    Ok(Some(crate::mcp_connections::Transport::Stdio {
        command,
        args,
        env,
    }))
}

